#!/usr/bin/env python3
"""Create a grouped comparison plot for IPC file-transfer benchmarks."""

import argparse
import csv
import math
import statistics
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Patch

BUFFER_CASES = ("small", "medium", "large")
MECHANISMS = {
    "sysv_shm": ("Разделяемая память", "#4778A8"),
    "sysv_queue": ("Очередь сообщений", "#E58B3A"),
    "fifo": ("FIFO", "#4D9A78"),
}


def format_bytes(size):
    """Format a size using binary units."""
    for factor, unit in ((1024**3, "ГиБ"), (1024**2, "МиБ"), (1024, "КиБ")):
        if size >= factor:
            value = size / factor
            if math.isclose(value, round(value), abs_tol=1e-9):
                return f"{int(round(value))} {unit}"
            return f"{value:.1f} {unit}"
    return f"{size} Б"


def read_results(csv_path):
    """Read and validate samples generated by run_benchmark.sh."""
    required = {
        "mechanism", "buffer_case", "buffer_size", "file_size_bytes",
        "run", "real_seconds",
    }
    samples = defaultdict(list)
    buffer_sizes = {}
    queue_chunk_sizes = {}
    file_sizes = set()
    seen = set()

    with csv_path.open(newline="", encoding="utf-8-sig") as csv_file:
        reader = csv.DictReader(csv_file)
        fields = set(reader.fieldnames or [])
        missing = required - fields
        if missing:
            raise ValueError("CSV is missing columns: " + ", ".join(sorted(missing)))

        for line, row in enumerate(reader, start=2):
            try:
                mechanism = row["mechanism"]
                case = row["buffer_case"]
                buffer_size = int(row["buffer_size"])
                file_size = int(row["file_size_bytes"])
                run_number = int(row["run"])
                seconds = float(row["real_seconds"])
                raw_effective = row.get("effective_chunk_size", "")
                effective_size = int(raw_effective) if raw_effective else buffer_size
            except (TypeError, ValueError) as error:
                raise ValueError(f"Invalid CSV row {line}: {error}") from error

            if mechanism not in MECHANISMS:
                raise ValueError(f"Unknown mechanism '{mechanism}' on CSV row {line}")
            if case not in BUFFER_CASES:
                raise ValueError(f"Unknown buffer case '{case}' on CSV row {line}")
            if min(buffer_size, file_size, run_number, effective_size) <= 0:
                raise ValueError(f"Sizes and run number must be positive on CSV row {line}")
            if not math.isfinite(seconds) or seconds < 0:
                raise ValueError(f"Invalid elapsed time on CSV row {line}")

            identity = (mechanism, case, run_number)
            if identity in seen:
                raise ValueError(f"Duplicate measurement {identity!r} on CSV row {line}")
            seen.add(identity)
            samples[(mechanism, case)].append(seconds)

            previous_size = buffer_sizes.get(case)
            if previous_size is not None and previous_size != buffer_size:
                raise ValueError(f"Inconsistent buffer size for '{case}' on CSV row {line}")
            buffer_sizes[case] = buffer_size
            file_sizes.add(file_size)

            if mechanism == "sysv_queue":
                previous_effective = queue_chunk_sizes.get(case)
                if previous_effective is not None and previous_effective != effective_size:
                    raise ValueError(
                        f"Inconsistent effective queue chunk size for '{case}' on CSV row {line}"
                    )
                queue_chunk_sizes[case] = effective_size

    if not samples:
        raise ValueError("CSV contains no measurements")
    if len(file_sizes) != 1:
        raise ValueError("Use measurements for one fixed input file size per plot")
    missing_cases = set(BUFFER_CASES) - set(buffer_sizes)
    if missing_cases:
        raise ValueError("CSV is missing buffer cases: " + ", ".join(sorted(missing_cases)))

    return file_sizes.pop(), samples, buffer_sizes, queue_chunk_sizes


def quartiles(values):
    """Return inclusive first and third quartiles, handling a single sample."""
    if len(values) < 2:
        return values[0], values[0]
    first, _, third = statistics.quantiles(values, n=4, method="inclusive")
    return first, third


def plot_results(file_size, samples, buffer_sizes, queue_chunk_sizes, output_path):
    """Plot medians, interquartile ranges, and individual measurements."""
    available_mechanisms = [
        key for key in MECHANISMS
        if any((key, case) in samples for case in BUFFER_CASES)
    ]
    absent_mechanisms = [key for key in MECHANISMS if key not in available_mechanisms]
    if not available_mechanisms:
        raise ValueError("No recognized IPC measurements to plot")

    x_positions = list(range(len(BUFFER_CASES)))
    group_width = 0.78
    bar_width = group_width / len(MECHANISMS)
    all_values = [value for values in samples.values() for value in values]
    max_value = max(all_values)
    y_max = max_value * 1.38 if max_value > 0 else 0.01

    fig, axis = plt.subplots(figsize=(11.5, 7.0))
    fig.subplots_adjust(left=0.10, right=0.97, top=0.82, bottom=0.26)

    fig.suptitle(
        "Сравнение времени передачи файла",
        fontsize=19,
        fontweight="bold",
        x=0.10,
        ha="left",
    )
    fig.text(
        0.10,
        0.885,
        f"Размер файла: {format_bytes(file_size)} · медиана времени real",
        fontsize=11,
        color="#505A66",
    )

    for mechanism_index, mechanism in enumerate(available_mechanisms):
        label, color = MECHANISMS[mechanism]
        offset = (mechanism_index - (len(available_mechanisms) - 1) / 2) * bar_width
        legend_added = False

        for group_index, case in enumerate(BUFFER_CASES):
            values = samples.get((mechanism, case))
            if not values:
                continue

            x = x_positions[group_index] + offset
            median = statistics.median(values)
            first_quartile, third_quartile = quartiles(values)

            axis.bar(
                x,
                median,
                width=bar_width * 0.82,
                color=color,
                alpha=0.92,
                edgecolor="white",
                linewidth=0.8,
                label=label if not legend_added else "",
                zorder=2,
            )
            legend_added = True

            # Whiskers show the interquartile range; individual dots below show
            # all runs, so outliers are visible rather than hidden by the median.
            axis.errorbar(
                x,
                median,
                yerr=[[max(0.0, median - first_quartile)],
                      [max(0.0, third_quartile - median)]],
                fmt="none",
                ecolor="#252D36",
                elinewidth=1.3,
                capsize=4,
                capthick=1.3,
                zorder=4,
            )

            jitter_step = min(0.025, (bar_width * 0.65) / max(1, len(values)))
            for sample_index, sample in enumerate(values):
                jitter = (sample_index - (len(values) - 1) / 2) * jitter_step
                axis.scatter(
                    [x + jitter],
                    [sample],
                    s=23,
                    color="#202833",
                    edgecolors="white",
                    linewidths=0.4,
                    zorder=5,
                )

            label_y = min(max(values) + y_max * 0.018, y_max * 0.94)
            axis.text(
                x,
                label_y,
                f"{median:.3f} s\nn={len(values)}",
                ha="center",
                va="bottom",
                fontsize=8.3,
                color="#26313D",
            )

    handles, labels = axis.get_legend_handles_labels()
    for mechanism in absent_mechanisms:
        label, _ = MECHANISMS[mechanism]
        handles.append(Patch(facecolor="#DDE1E6", edgecolor="#9AA3AD", hatch="///"))
        labels.append(f"{label} — нет замеров")
    axis.legend(
        handles,
        labels,
        ncols=min(3, len(labels)),
        frameon=False,
        loc="upper left",
        bbox_to_anchor=(0, 1.02),
        fontsize=10,
    )

    tick_labels = [
        f"{case.capitalize()}\n{format_bytes(buffer_sizes[case])}"
        for case in BUFFER_CASES
    ]
    axis.set_xticks(x_positions, tick_labels, fontsize=10)
    axis.set_xlim(-0.55, len(BUFFER_CASES) - 0.45)
    axis.set_ylim(0, y_max)
    axis.set_ylabel("Время передачи, секунды", fontsize=11)
    axis.set_xlabel("Размер буфера приложения", labelpad=12, fontsize=11)
    axis.grid(axis="y", linestyle=(0, (3, 3)), linewidth=0.8, color="#D9DEE5", zorder=0)
    axis.set_axisbelow(True)
    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)
    axis.spines["left"].set_color("#ABB3BD")
    axis.spines["bottom"].set_color("#ABB3BD")
    axis.tick_params(axis="both", length=0, colors="#343C46")

    footer = (
        "Столбец — медиана; вертикальные интервалы — интерквартильный диапазон (Q1–Q3); "
        "точки — отдельные измерения."
    )
    if queue_chunk_sizes:
        chunk_details = "; ".join(
            f"{case}: {format_bytes(queue_chunk_sizes[case])}"
            for case in BUFFER_CASES if case in queue_chunk_sizes
        )
        footer += f"\nФактическая полезная нагрузка сообщения очереди: {chunk_details}."
    if "fifo" in absent_mechanisms:
        footer += "\nFIFO пока не включён в текущий запуск бенчмарка."

    fig.text(
        0.10,
        0.12,
        footer,
        ha="left",
        va="top",
        fontsize=9,
        color="#58616C",
        linespacing=1.6,
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, dpi=180, facecolor="white")
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--output-name", default="transfer_times.png")
    args = parser.parse_args()

    try:
        file_size, samples, buffer_sizes, queue_chunks = read_results(args.csv)
        args.output_dir.mkdir(parents=True, exist_ok=True)
        output_path = args.output_dir / args.output_name
        plot_results(file_size, samples, buffer_sizes, queue_chunks, output_path)
    except (OSError, ValueError) as error:
        parser.error(str(error))

    print(f"Diagram saved to {output_path}")


if __name__ == "__main__":
    main()

